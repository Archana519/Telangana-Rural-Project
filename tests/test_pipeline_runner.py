def test_flow_figure_panels_render_without_network(tmp_path):
    F = load("build_paper_flow_figure")
    import matplotlib.pyplot as plt
    from tests.test_clearance import CRS, run, world_data
    ha, out = run([(300, 100, 30, 340)], [(700, 450, 20, 20), (650, 300, 20, 20)], fac=[(800, 700, 20, 20)])
    _, gap, f, roads = world_data([(300, 100, 30, 340)], [(700, 450, 20, 20), (650, 300, 20, 20)], fac=[(800, 700, 20, 20)])
    cell = box(500000.0, 1900000.0, 501000.0, 1901000.0)
    sc = MM.scene_from_clearance("Test", "synthetic", cell, gpd.GeoSeries(roads, crs=CRS), ha, gap, f, out, mosaic=None)
    ext = F.square_ext(cell)
    img = (np.full((50, 50, 4), 120, dtype="uint8"), (ext[0], ext[2], ext[1], ext[3]))
    fig, axs = plt.subplots(1, 3, figsize=(6, 2.2))
    for ax, kind in zip(axs[:2], ("input", "output")):
        F.panel(ax, sc, ext, img, kind, F.nice_scale(ext[2] - ext[0]))
    F.figure_legend(fig)
    p = tmp_path / "t.png"
    fig.savefig(p, dpi=60)
    assert p.stat().st_size > 3000
    assert F.nice_scale(5000) == 1000 and F.nice_scale(1200) == 200


def test_stage_a_is_drawn_above_the_shared_network_with_a_dashed_underlay():
    import matplotlib.pyplot as plt
    from tests.test_clearance import CRS, run, world_data
    ha, out = run([(300, 100, 30, 340)], [(700, 450, 20, 20), (650, 300, 20, 20)], fac=[(800, 700, 20, 20)])
    _, gap, f, roads = world_data([(300, 100, 30, 340)], [(700, 450, 20, 20), (650, 300, 20, 20)], fac=[(800, 700, 20, 20)])
