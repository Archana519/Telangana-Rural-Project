def test_slope_percent_is_100_tan_of_slope():
    s = np.full((5, 5), 45.0, dtype="float32")
    mean, mx = PS.slope_percent_stats(s, np.ones((5, 5), bool))
    assert mean == pytest.approx(100.0, abs=1e-3) and mx == pytest.approx(100.0, abs=1e-3)
    assert PS.slope_percent_stats(s, np.zeros((5, 5), bool)) == (None, None)


