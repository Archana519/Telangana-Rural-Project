"""Generate paper_ieee/main.tex (IEEEtran journal) from the SAME content calls as build_ieee_docx.py, so text, tables, figures and
citations are identical to IEEE_Journal_Manuscript.docx.  Run: python paper_ieee/build_ieee_tex.py"""
import re
from pathlib import Path
H = Path(__file__).resolve().parent
src = (H / "build_ieee_docx.py").read_text(encoding="utf-8")
abs_txt = eval("(" + re.search(r"ABS = \((.*?)\)\np = doc", src, re.S).group(1) + ")")
kw_txt = re.search(r'"\*Index Terms\*—(.*?)"', src).group(1)
body = src[src.index("# =====================================================================  I. INTRODUCTION"):src.index('H1u("References")')]

MAP = {"μ": r"$\mu$", "ℓ": r"$\ell$", "π": r"$\pi$", "∈": r"$\in$", "∖": r"$\setminus$", "Σ": r"$\Sigma$", "Δ": r"$\Delta$", "κ": r"$\kappa$",
       "ρ": r"$\rho$", "δ": r"$\delta$", "≥": r"$\geq$", "≈": r"$\approx$", "°": r"\textdegree{}", "×": r"$\times$", "–": "--", "—": "---",
       "−": r"$-$", "→": r"$\rightarrow$", "·": r"$\cdot$", "|": r"$|$", "é": r"\'e", "’": "'"}
ESC = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_", "$": r"\$", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
TOK = re.compile(r"(\*\*.+?\*\*|\*.+?\*|_\{.+?\}|\^\{.+?\})")
def esc(s):
    return "".join(MAP.get(c) or ESC.get(c) or c for c in s)
def conv(text):
    out = []
    for seg in re.split(r"(<<[^>]+>>)", text):
        if seg.startswith("<<"):
            out.append("\\cite{" + ",".join(k.strip() for k in seg[2:-2].split(",")) + "}"); continue
        for part in TOK.split(seg):
            if not part: continue
            if part.startswith("**"): out.append(r"\textbf{" + conv(part[2:-2]) + "}")
            elif part.startswith("*"): out.append(r"\textit{" + esc(part[1:-1]) + "}")
            elif part.startswith("_{"): out.append(r"\textsubscript{" + esc(part[2:-1]) + "}")
            elif part.startswith("^{"): out.append(r"\textsuperscript{" + esc(part[2:-1]) + "}")
            else: out.append(esc(part))
    return "".join(out)

L = []
cnt = {"fig": 0, "tab": 0}
def H1(t): L.append(f"\n\\section{{{conv(t)}}}")
def H1u(t): L.append(f"\n\\section*{{{conv(t)}}}")
def H2(t): L.append(f"\n\\subsection{{{conv(t)}}}")
def P(t, first=0.17, after=0): L.append("\n" + conv(t))
def BUL(items):
    L.append("\\begin{enumerate}")
    for t in items: L.append("\\item " + conv(t))
    L.append("\\end{enumerate}")
EQS = {1: r"c(x) = \bigl[\, c_{\mathrm{lc}}(\ell(x)) + g(s(x)) \,\bigr]\, m(x)",
       2: r"\Delta L_{\mathrm{cost}}(\pi \mid S) = \sum_{e \in \pi \setminus E_S} w(e)"}
def EQ(t, n): L.append("\\begin{equation}\n" + EQS[n] + "\n\\label{eq:%d}\n\\end{equation}" % n)
def one_col(): pass
def two_col(): pass
def FIGURE(fn, cap, width):
    cnt["fig"] += 1
    env = "figure"
    w = r"\columnwidth"
    L.append(f"\n\\begin{{{env}}}[!t]\n\\centering\n\\includegraphics[width={w}]{{figures/{fn}}}\n\\caption{{{conv(cap)}}}\n\\label{{fig:{cnt['fig']}}}\n\\end{{{env}}}")
def TABLE(title, header, rows, widths, bold_rows=(), sub_rows=(), size=8, align=None):
    cnt["tab"] += 1
    wide = False; n = len(header)
    avail = 3.3 - n * 0.056
    tot = sum(widths); ws = [w * avail / tot for w in widths]
    cols = "".join((r">{\raggedright\arraybackslash}" if i == 0 or header[0] == "Layer" else r">{\raggedleft\arraybackslash}") + f"p{{{w:.3f}in}}" for i, w in enumerate(ws))
    env = "table*" if wide else "table"
    fs = r"\scriptsize" if size < 8 else r"\footnotesize"
    L.append(f"\n\\begin{{{env}}}[!t]\n\\caption{{{conv(title)}}}\n\\label{{tab:{cnt['tab']}}}\n\\centering\n{fs}\n\\setlength{{\\tabcolsep}}{{2pt}}\n\\begin{{tabular}}{{{cols}}}\n\\toprule")
    L.append(" & ".join(r"\textbf{" + conv(h) + "}" if h else "" for h in header) + r" \\")
    L.append(r"\midrule")
    for ri, row in enumerate(rows):
        if ri in sub_rows: L.append(r"\multicolumn{%d}{@{}l}{\textit{%s}} \\" % (n, conv(row[0])))
        else: L.append(" & ".join(conv(c.strip() if i == 0 and False else c) for i, c in enumerate(row)) + r" \\")
    L.append(f"\\bottomrule\n\\end{{tabular}}\n\\end{{{env}}}")
def C(t): return t
ns = dict(CR="(Basemap imagery: Esri, Maxar, Earthstar Geographics, and the GIS User Community).", H1=H1, H1u=H1u, H2=H2, P=P, BUL=BUL, EQ=EQ, FIGURE=FIGURE, TABLE=TABLE, one_col=one_col, two_col=two_col, C=C)
exec(body, ns)

