"""
Damarakunta Route Connectivity Validation V4

Uses the actual fields in damarakunta_routes_v3.gpkg.
Writes separate V4 output files; does not modify V3 inputs or outputs.

Important:
- Geometric intersections do not prove that a road is legally usable or navigable.
- Facility coordinates and entrances remain unverified.
- Distances use the projected metric CRS EPSG:32644.
"""

from pathlib import Path
import sys

import geopandas as gpd
import pandas as pd
from shapely.geometry import Point
from shapely.ops import unary_union

ROOT = Path(r"D:\Telangana_Rural_Project")
BASE = ROOT / "Siddipet" / "Damarakunta"

ROADS_PATH = BASE / "reference" / "tgrac_road_network.gpkg"
FACILITIES_PATH = BASE / "reference" / "damarakunta_priority_facilities.gpkg"
ROUTES_PATH = BASE / "results" / "damarakunta_routes_v3.gpkg"

OUT_CSV = BASE / "results" / "damarakunta_route_connectivity_validation_v4.csv"
OUT_GPKG = BASE / "results" / "damarakunta_route_connectivity_validation_v4.gpkg"
OUT_TXT = BASE / "results" / "damarakunta_route_connectivity_validation_v4_README.txt"

CRS_METRIC = "EPSG:32644"
ROAD_ENDPOINT_TOLERANCE_M = 5.0
FACILITY_ENDPOINT_TOLERANCE_M = 5.0
INTERSECTION_EPSILON_M = 0.01


def fail(message):
    print("\nERROR:", message)
    sys.exit(1)


def load_layer(path, label):
    if not path.exists():
        fail(f"{label} not found:\n{path}")
    try:
        gdf = gpd.read_file(path)
    except Exception as exc:
        fail(f"Could not read {label}: {exc}")
    if gdf.empty:
        fail(f"{label} has no features.")
    if gdf.crs is None:
        fail(f"{label} has no CRS; refusing to calculate distances.")
    gdf = gdf[gdf.geometry.notna() & ~gdf.geometry.is_empty].copy()
    if gdf.empty:
        fail(f"{label} has no usable geometries.")
    return gdf


def choose_column(gdf, candidates, label, required=True):
    lower = {str(col).lower(): col for col in gdf.columns}
    for candidate in candidates:
        if candidate.lower() in lower:
            return lower[candidate.lower()]
    if required:
        fail(f"Cannot identify {label}. Available fields: {list(gdf.columns)}")
    return None


def route_line_parts(geom):
    if geom is None or geom.is_empty:
        return []
    if geom.geom_type == "LineString":
        return [geom]
    if geom.geom_type == "MultiLineString":
        return list(geom.geoms)
    if geom.geom_type == "GeometryCollection":
        parts = []
        for part in geom.geoms:
            parts.extend(route_line_parts(part))
        return parts
    return []


def as_text(value):
    if value is None or pd.isna(value):
        return ""
    return str(value).strip()


def analyze_route(route_geom, facility_geom, roads_union):
    parts = route_line_parts(route_geom)
    if not parts:
        return {
            "geometry_valid": False,
            "route_geometry_type": getattr(route_geom, "geom_type", "EMPTY"),
            "route_length_m": None,
            "endpoint_a_to_facility_m": None,
            "endpoint_b_to_facility_m": None,
            "nearest_facility_endpoint": "",
            "nearest_facility_endpoint_gap_m": None,
            "other_endpoint_to_road_m": None,
            "endpoint_a_to_road_m": None,
            "endpoint_b_to_road_m": None,
            "route_to_road_geometry_m": None,
            "route_intersects_road": False,
            "intersection_type": "NO_VALID_LINE_GEOMETRY",
            "intersection_length_m": 0.0,
            "intersection_point_count": 0,
            "facility_endpoint_check": "NOT_CHECKED",
            "road_endpoint_check": "NOT_CHECKED",
            "connectivity_screening_status": "INVALID_OR_NON_LINE_ROUTE",
        }

    # Routes generated by the current workflow are expected to be LineStrings.
    # For multipart geometries, this uses the first part's start and last part's end.
    # Such multipart routes are explicitly flagged for review.
    route_union = unary_union(parts)
    endpoint_a = Point(parts[0].coords[0])
    endpoint_b = Point(parts[-1].coords[-1])

    d_a_fac = float(endpoint_a.distance(facility_geom))
    d_b_fac = float(endpoint_b.distance(facility_geom))
    if d_a_fac <= d_b_fac:
        nearest_endpoint = "A"
        facility_gap = d_a_fac
        other_endpoint = endpoint_b
    else:
        nearest_endpoint = "B"
        facility_gap = d_b_fac
        other_endpoint = endpoint_a

    d_a_road = float(endpoint_a.distance(roads_union))
    d_b_road = float(endpoint_b.distance(roads_union))
    other_road_gap = float(other_endpoint.distance(roads_union))
    route_road_gap = float(route_union.distance(roads_union))

    intersection = route_union.intersection(roads_union)
    intersects = not intersection.is_empty
    intersection_length = float(intersection.length) if intersects else 0.0

    # Count distinct point components in the intersection geometry.
    point_geometries = []

    def collect_points(geom):
        if geom is None or geom.is_empty:
            return
        if geom.geom_type == "Point":
            point_geometries.append(geom)
        elif geom.geom_type in ("MultiPoint", "GeometryCollection"):
            for subgeom in geom.geoms:
                collect_points(subgeom)
        elif geom.geom_type in ("LineString", "MultiLineString"):
            # Line intersections are reported as overlap, not point contacts.
            return

    collect_points(intersection)
    unique_points = []
    for point in point_geometries:
        if not any(point.distance(existing) <= INTERSECTION_EPSILON_M for existing in unique_points):
            unique_points.append(point)

    if not intersects:
        intersection_type = "NO_INTERSECTION"
    elif intersection_length > INTERSECTION_EPSILON_M:
        intersection_type = "LINE_OVERLAP"
    elif len(unique_points) > 0:
        intersection_type = "POINT_CONTACT_ONLY"
    else:
        intersection_type = "INTERSECTION_PRESENT_REVIEW_GEOMETRY"

    facility_ok = facility_gap <= FACILITY_ENDPOINT_TOLERANCE_M
    road_ok = other_road_gap <= ROAD_ENDPOINT_TOLERANCE_M

    facility_status = (
        "WITHIN_SCREENING_TOLERANCE"
        if facility_ok else "FACILITY_ENDPOINT_GAP_REMAINS"
    )
    road_status = (
        "WITHIN_SCREENING_TOLERANCE"
        if road_ok else "ROAD_ENDPOINT_GAP_REMAINS"
    )

    if len(parts) > 1:
        status = "MULTIPART_ROUTE_REQUIRES_REVIEW"
    elif not facility_ok and not road_ok:
        status = "FACILITY_AND_ROAD_ENDPOINT_GAPS_REMAIN"
    elif not facility_ok:
        status = "FACILITY_ENDPOINT_GAP_REMAINS"
    elif not road_ok:
        status = "ROAD_ENDPOINT_GAP_REMAINS"
    elif intersection_type == "POINT_CONTACT_ONLY":
        status = "POTENTIAL_POINT_CONNECTION_TO_ROAD_REQUIRES_TOPOLOGY_REVIEW"
    elif intersection_type == "LINE_OVERLAP":
        status = "ROAD_OVERLAP_PRESENT_REQUIRES_TOPOLOGY_REVIEW"
    elif intersection_type == "NO_INTERSECTION":
        status = "ENDPOINTS_WITHIN_TOLERANCE_BUT_NO_INTERSECTION"
    else:
        status = "INTERSECTION_PRESENT_REQUIRES_REVIEW"

    return {
        "geometry_valid": bool(route_geom.is_valid),
        "route_geometry_type": route_geom.geom_type,
        "route_length_m": float(route_geom.length),
        "endpoint_a_to_facility_m": d_a_fac,
        "endpoint_b_to_facility_m": d_b_fac,
        "nearest_facility_endpoint": nearest_endpoint,
        "nearest_facility_endpoint_gap_m": facility_gap,
        "other_endpoint_to_road_m": other_road_gap,
        "endpoint_a_to_road_m": d_a_road,
        "endpoint_b_to_road_m": d_b_road,
        "route_to_road_geometry_m": route_road_gap,
        "route_intersects_road": bool(intersects),
        "intersection_type": intersection_type,
        "intersection_length_m": intersection_length,
        "intersection_point_count": len(unique_points),
        "facility_endpoint_check": facility_status,
        "road_endpoint_check": road_status,
        "connectivity_screening_status": status,
    }


def main():
    print("=== DAMARAKUNTA ROUTE CONNECTIVITY VALIDATION V4 ===")
    print("Loading existing V3 route layer, roads, and facilities...")

    roads = load_layer(ROADS_PATH, "Existing road network")
    facilities = load_layer(FACILITIES_PATH, "Priority facilities")
    routes = load_layer(ROUTES_PATH, "V3 route alternatives")

    # Distances are meaningful only in a projected CRS measured in metres.
    roads = roads.to_crs(CRS_METRIC)
    facilities = facilities.to_crs(CRS_METRIC)
    routes = routes.to_crs(CRS_METRIC)

    required_route_fields = ["facility_id", "facility_name", "alternative", "status"]
    missing = [field for field in required_route_fields if field not in routes.columns]
    if missing:
        fail(f"Route layer is missing expected V3 fields: {missing}")

    fac_name_col = choose_column(
        facilities,
        ["facility_name", "name", "facility", "NAME", "FACILITY_NAME"],
        "facility name",
        required=False,
    )
    fac_id_col = choose_column(
        facilities,
        ["facility_id", "id", "NIN_ID", "OBJECTID", "fid"],
        "facility ID",
        required=False,
    )
    if fac_name_col is None and fac_id_col is None:
        fail("Cannot identify facility name or ID fields in the facility layer.")

    facility_records = []
    for index, row in facilities.iterrows():
        facility_records.append({
            "id": as_text(row[fac_id_col]) if fac_id_col else "",
            "name": as_text(row[fac_name_col]) if fac_name_col else "",
            "geometry": row.geometry,
        })

    roads_union = unary_union(list(roads.geometry))
    rows = []
    output_geometries = []

    for index, route_row in routes.iterrows():
        route_id = as_text(route_row["facility_id"])
        route_name = as_text(route_row["facility_name"])

        matches = []
        if route_id and fac_id_col:
            matches = [f for f in facility_records if f["id"] == route_id]
        match_method = "EXACT_ID" if matches else ""

        if not matches and route_name and fac_name_col:
            matches = [
                f for f in facility_records
                if f["name"].strip().lower() == route_name.strip().lower()
            ]
            if matches:
                match_method = "EXACT_NAME"

        if matches:
            facility = matches[0]
        else:
            # Do not silently select a nearest facility: report the unresolved match.
            result = analyze_route(route_row.geometry, route_row.geometry, roads_union)
            result.update({
                "source_route_index": str(index),
                "facility_id": route_id,
                "facility_name": route_name,
                "alternative": as_text(route_row["alternative"]),
                "source_route_status": as_text(route_row["status"]),
                "facility_match_method": "NO_MATCH_FOUND",
                "facility_coordinate_independently_verified": "NO",
                "topology_verified": "NO",
                "ownership_verified": "NO",
                "construction_feasibility": "NOT_ASSESSED",
                "screening_note": "Facility match failed; facility-distance fields are not valid for interpretation.",
            })
            rows.append(result)
            output_geometries.append(route_row.geometry)
            continue

        result = analyze_route(route_row.geometry, facility["geometry"], roads_union)
        result.update({
            "source_route_index": str(index),
            "facility_id": route_id,
            "facility_name": route_name,
            "alternative": as_text(route_row["alternative"]),
            "source_route_status": as_text(route_row["status"]),
            "facility_match_method": match_method,
            "facility_coordinate_independently_verified": "NO",
            "topology_verified": "NO",
            "ownership_verified": "NO",
            "construction_feasibility": "NOT_ASSESSED",
            "screening_note": (
                "Geometric screening only. Verify facility entrance, route topology, "
                "building clearance, drainage, land ownership, and engineering feasibility."
            ),
        })
        rows.append(result)
        output_geometries.append(route_row.geometry)

    report = pd.DataFrame(rows)
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    report.to_csv(OUT_CSV, index=False, encoding="utf-8-sig")

    result_gdf = gpd.GeoDataFrame(report, geometry=output_geometries, crs=CRS_METRIC)
    # Normalize pandas nullable values for GeoPackage compatibility.
    for col in result_gdf.columns:
        if col == "geometry":
            continue
        if result_gdf[col].dtype == "object":
            result_gdf[col] = result_gdf[col].map(
                lambda value: None if value is pd.NA else value
            )
    result_gdf.to_file(OUT_GPKG, layer="connectivity_validation_v4", driver="GPKG")

    counts = report["connectivity_screening_status"].value_counts(dropna=False)
    summary = [
        "DAMARAKUNTA ROUTE CONNECTIVITY VALIDATION V4",
        "",
        f"Routes checked: {len(report)}",
        f"Road features read: {len(roads)}",
        f"Facility features read: {len(facilities)}",
        f"Measurement CRS: {CRS_METRIC}",
        f"Facility endpoint screening tolerance: {FACILITY_ENDPOINT_TOLERANCE_M} m",
        f"Road endpoint screening tolerance: {ROAD_ENDPOINT_TOLERANCE_M} m",
        "",
        "Connectivity screening status counts:",
        counts.to_string(),
        "",
        "Intersection type counts:",
        report["intersection_type"].value_counts(dropna=False).to_string(),
        "",
        "LIMITATIONS",
        "- Geometric proximity/intersection is not proof of a navigable road network.",
        "- Facility coordinates and entrances are not independently verified.",
        "- Ownership, drainage, building clearance, and construction feasibility are not assessed.",
        "- Review route geometries and official records before selecting a preferred route.",
        "",
        f"CSV output: {OUT_CSV}",
        f"GeoPackage output: {OUT_GPKG}",
    ]
    OUT_TXT.write_text("\n".join(summary), encoding="utf-8")

    print("\nValidation complete.")
    print(f"Routes checked: {len(report)}")
    print(f"CSV: {OUT_CSV}")
    print(f"GeoPackage: {OUT_GPKG}")
    print(f"Summary: {OUT_TXT}")
    print("\nConnectivity screening status:")
    print(counts.to_string())
    print("\nIntersection types:")
    print(report["intersection_type"].value_counts(dropna=False).to_string())
    print("\nReminder: this is geometric screening, not verified network connectivity.")


if __name__ == "__main__":
    main()
