
from pathlib import Path

import numpy as np
import geopandas as gpd
import matplotlib.pyplot as plt
import rasterio
from rasterio.enums import Resampling

# ============================================================
# 1. PROJECT PATHS
# ============================================================

BASE = Path(r"D:\Telangana_Rural_Project\Siddipet\Damarakunta")
ALIGNED = BASE / "aligned"
REF = BASE / "reference"
RESULTS = BASE / "results"

IMAGERY = ALIGNED / "damarakunta_esri_highres_mosaic_0p6m.tif"
BOUNDARY = BASE / "study_area" / "damarakunta_boundary.gpkg"

ROADS = REF / "tgrac_road_network.gpkg"
FACILITIES = REF / "damarakunta_priority_facilities.gpkg"
SCHOOLS = REF / "school_compounds_utm44n.gpkg"

# Use the latest V2 routes.
ROUTES = RESULTS / "damarakunta_routes_v2.gpkg"

# Generated by the feasibility-screening script.
PARCEL_IMPACTS = RESULTS / "damarakunta_route_parcel_impacts.gpkg"

OUT_MAP = RESULTS / "damarakunta_feasibility_map.png"
OUT_ZOOM = RESULTS / "damarakunta_feasibility_zoom.png"

CRS = "EPSG:32644"

# Do not overwrite previous maps.
# If you want a new version, change the output filenames above.


# ============================================================
# 2. HELPER FUNCTIONS
# ============================================================

def read_layer(path):
    """Read a vector layer and reproject it to the project CRS."""
    gdf = gpd.read_file(path)

    if gdf.crs is None:
        raise ValueError(f"Missing CRS: {path}")

    gdf = gdf.to_crs(CRS)

    return gdf[
        gdf.geometry.notna() & ~gdf.geometry.is_empty
    ].copy()


def get_facility_name(row):
    """Return a readable facility name."""
    return str(
        row.get(
            "facility_name",
            row.get("name", "Facility")
        )
    )


def get_facility_type(row):
    """Return a readable facility type."""
    return str(row.get("facility_type", "Facility"))


def draw_routes(ax, routes, line_width=3.0):
    """Draw proposed routes with a white outline for visibility."""
    for _, row in routes.iterrows():
        geom = row.geometry

        if geom is None or geom.is_empty:
            continue

        if geom.geom_type == "LineString":
            lines = [geom]
        elif geom.geom_type == "MultiLineString":
            lines = list(geom.geoms)
        else:
            continue

        for line in lines:
            x, y = line.xy

            ax.plot(
                x, y,
                color="white",
                linewidth=line_width + 2.2,
                alpha=0.95,
                zorder=6,
                solid_capstyle="round",
            )

            ax.plot(
                x, y,
                color="#ff1744",
                linewidth=line_width,
                alpha=1.0,
                zorder=7,
                solid_capstyle="round",
            )


def draw_facilities(ax, facilities, label_all=True):
    """Draw facility points and optional labels."""
    type_colors = {
        "School": "#2563eb",
        "Healthcare": "#7c3aed",
        "Anganwadi": "#d97706",
    }

    offsets = [
        (12, 12),
        (12, -24),
        (15, 16),
        (15, -25),
        (-100, 16),
        (-100, -25),
    ]

    for i, (_, row) in enumerate(facilities.iterrows()):
        geom = row.geometry

        if geom is None or geom.is_empty or geom.geom_type != "Point":
            continue

        name = get_facility_name(row)
        typ = get_facility_type(row)
        color = type_colors.get(typ, "#0f766e")

        ax.scatter(
            [geom.x],
            [geom.y],
            s=165,
            marker="o",
            c=color,
            edgecolors="white",
            linewidths=2,
            zorder=10,
        )

        ax.scatter(
            [geom.x],
            [geom.y],
            s=35,
            marker="o",
            c="white",
            edgecolors="none",
            zorder=11,
        )

        if label_all:
            dx, dy = offsets[i % len(offsets)]

            ax.annotate(
                f"{name}\n({typ})",
                xy=(geom.x, geom.y),
                xytext=(dx, dy),
                textcoords="offset points",
                fontsize=8,
                fontweight="bold",
                color="black",
                zorder=12,
                bbox=dict(
                    boxstyle="round,pad=0.3",
                    fc="white",
                    ec=color,
                    alpha=0.96,
                ),
                arrowprops=dict(
                    arrowstyle="-",
                    color=color,
                    lw=1.1,
                ),
            )


def draw_parcel_impacts(ax, impacts):
    """Highlight route/parcel intersection geometries."""
    if impacts.empty:
        return

    impacts.plot(
        ax=ax,
        color="#ffcc00",
        edgecolor="#ffb300",
        linewidth=1.8,
        alpha=0.95,
        zorder=5,
    )


def draw_school_compounds(ax, schools):
    """Outline school compounds for visual inspection."""
    if schools.empty:
        return

    schools.boundary.plot(
        ax=ax,
        color="#00e676",
        linewidth=1.8,
        alpha=0.95,
        zorder=4,
    )


def draw_roads(ax, roads, linewidth=1.1):
    """Draw existing roads."""
    if roads.empty:
        return

    roads.plot(
        ax=ax,
        color="#00e5ff",
        linewidth=linewidth,
        alpha=0.95,
        zorder=3,
    )


def style_axes(ax, title):
    ax.set_aspect("equal", adjustable="box")
    ax.set_title(title, fontsize=13, pad=12)
    ax.set_xlabel("Easting (m, EPSG:32644)")
    ax.set_ylabel("Northing (m, EPSG:32644)")
    ax.grid(False)


# ============================================================
# 3. MAIN PROCESS
# ============================================================

def main():
    RESULTS.mkdir(parents=True, exist_ok=True)

    required = [
        IMAGERY,
        BOUNDARY,
        ROADS,
        FACILITIES,
        SCHOOLS,
        ROUTES,
        PARCEL_IMPACTS,
    ]

    missing = [str(path) for path in required if not path.exists()]

    if missing:
        raise FileNotFoundError(
            "Required input file(s) not found:\n"
            + "\n".join(missing)
        )

    existing_outputs = [
        path for path in [OUT_MAP, OUT_ZOOM] if path.exists()
    ]

    if existing_outputs:
        raise FileExistsError(
            "Map output(s) already exist. Rename or back them up first:\n"
            + "\n".join(str(path) for path in existing_outputs)
        )

    # --------------------------------------------------------
    # 3A. LOAD VECTOR LAYERS
    # --------------------------------------------------------

    boundary = read_layer(BOUNDARY)
    roads = read_layer(ROADS)
    facilities = read_layer(FACILITIES)
    schools = read_layer(SCHOOLS)
    routes = read_layer(ROUTES)
    parcel_impacts = read_layer(PARCEL_IMPACTS)

    if boundary.empty:
        raise ValueError("The village boundary layer is empty.")

    if routes.empty:
        raise ValueError("No usable V2 route geometries were found.")

    # Clip displayed roads to the village boundary.
    # Original source data are not modified.
    boundary_union = boundary.geometry.union_all()

    roads["geometry"] = roads.geometry.intersection(boundary_union)
    roads = roads[
        roads.geometry.notna() & ~roads.geometry.is_empty
    ].copy()

    # --------------------------------------------------------
    # 3B. LOAD AND DOWNSAMPLE SATELLITE IMAGERY
    # --------------------------------------------------------

    with rasterio.open(IMAGERY) as src:
        if src.crs is None:
            raise ValueError("Satellite imagery has no defined CRS.")

        if src.crs.to_string() != CRS:
            raise ValueError(
                f"Expected imagery CRS {CRS}; got {src.crs}"
            )

        scale = min(
            1.0,
            2800.0 / max(src.width, src.height)
        )

        height = max(1, int(src.height * scale))
        width = max(1, int(src.width * scale))

        image_array = src.read(
            [1, 2, 3],
            out_shape=(3, height, width),
            resampling=Resampling.bilinear,
        )

        extent = [
            src.bounds.left,
            src.bounds.right,
            src.bounds.bottom,
            src.bounds.top,
        ]

    image = np.moveaxis(image_array, 0, -1).astype(float)

    low, high = np.percentile(image, [2, 98])

    if high > low:
        image = np.clip(
            (image - low) / (high - low),
            0,
            1,
        )

    # --------------------------------------------------------
    # 3C. FULL VILLAGE FEASIBILITY MAP
    # --------------------------------------------------------

    minx, miny, maxx, maxy = boundary.total_bounds
    padding = 120

    fig, ax = plt.subplots(figsize=(15, 12))

    ax.imshow(
        image,
        extent=extent,
        origin="upper",
        zorder=0,
    )

    boundary.boundary.plot(
        ax=ax,
        color="white",
        linewidth=1.5,
        zorder=2,
    )

    draw_roads(ax, roads, linewidth=1.1)
    draw_school_compounds(ax, schools)
    draw_parcel_impacts(ax, parcel_impacts)
    draw_routes(ax, routes, line_width=3.0)
    draw_facilities(ax, facilities, label_all=True)

    ax.set_xlim(minx - padding, maxx + padding)
    ax.set_ylim(miny - padding, maxy + padding)

    style_axes(
        ax,
        "Damarakunta — Preliminary Route Feasibility Map\n"
        "Cyan: existing roads | Magenta: V2 candidate routes | "
        "Yellow: route–parcel intersections | Green: school compounds",
    )

    fig.tight_layout()
    fig.savefig(
        OUT_MAP,
        dpi=240,
        bbox_inches="tight",
    )
    plt.close(fig)

    # --------------------------------------------------------
    # 3D. FACILITY AND ROUTE CLOSE-UP
    # --------------------------------------------------------

    focus_geometries = [
        geom
        for geom in (
            list(facilities.geometry)
            + list(routes.geometry)
            + list(parcel_impacts.geometry)
        )
        if geom is not None and not geom.is_empty
    ]

    if focus_geometries:
        focus_bounds = gpd.GeoSeries(
            focus_geometries,
            crs=CRS,
        ).total_bounds

        fx0, fy0, fx1, fy1 = focus_bounds
        padding_zoom = 180

        fig, ax = plt.subplots(figsize=(14, 10))

        ax.imshow(
            image,
            extent=extent,
            origin="upper",
            zorder=0,
        )

        draw_roads(ax, roads, linewidth=1.3)
        draw_school_compounds(ax, schools)
        draw_parcel_impacts(ax, parcel_impacts)
        draw_routes(ax, routes, line_width=3.2)
        draw_facilities(ax, facilities, label_all=True)

        ax.set_xlim(fx0 - padding_zoom, fx1 + padding_zoom)
        ax.set_ylim(fy0 - padding_zoom, fy1 + padding_zoom)

        style_axes(
            ax,
            "Damarakunta — Facility and Route Close-up\n"
            "Inspect candidate alignments against parcels, "
            "school compounds, roofs and entrances",
        )

        fig.tight_layout()
        fig.savefig(
            OUT_ZOOM,
            dpi=260,
            bbox_inches="tight",
        )
        plt.close(fig)

    # --------------------------------------------------------
    # 4. REPORT
    # --------------------------------------------------------

    print("\n" + "=" * 65)
    print("DAMARAKUNTA FEASIBILITY MAP GENERATION COMPLETE")
    print("=" * 65)

    print(f"V2 route features: {len(routes)}")
    print(f"Facility records: {len(facilities)}")
    print(f"School compound features: {len(schools)}")
    print(f"Existing road features after clipping: {len(roads)}")
    print(f"Route-parcel intersection features: {len(parcel_impacts)}")

    print("\nGenerated maps:")
    print("Village map:", OUT_MAP)
    print("Facility close-up:", OUT_ZOOM)

    print("\nInterpretation limits:")
    print("- Yellow geometries show potential parcel intersections.")
    print("- They do not establish legal ownership or acquisition needs.")
    print("- Green outlines show school compounds, not verified entrances.")
    print("- Visual overlap does not establish construction feasibility.")
    print("- Drainage and building clearance remain unverified.")
    print("- These are preliminary screening maps, not construction approval.")


if __name__ == "__main__":
    main()
